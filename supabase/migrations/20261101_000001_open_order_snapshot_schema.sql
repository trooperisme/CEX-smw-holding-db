create table if not exists public.open_order_snapshots (
  id bigint generated by default as identity primary key,
  status text not null check (status in ('running', 'success', 'partial', 'failed')),
  source text not null,
  total_wallets integer not null default 0,
  successful_wallets integer not null default 0,
  failed_wallets integer not null default 0,
  total_orders integer not null default 0,
  captured_at timestamptz not null,
  error_message text,
  created_at timestamptz not null default timezone('utc', now()),
  finished_at timestamptz
);

create table if not exists public.open_order_wallet_runs (
  id bigint generated by default as identity primary key,
  snapshot_id bigint not null references public.open_order_snapshots(id) on delete cascade,
  trader_name text not null,
  wallet_address text not null,
  source_url text not null,
  status text not null check (status in ('success', 'failed')),
  orders_found integer not null default 0,
  error_message text,
  unique (snapshot_id, wallet_address)
);

create table if not exists public.open_orders (
  id bigint generated by default as identity primary key,
  snapshot_id bigint not null references public.open_order_snapshots(id) on delete cascade,
  trader_name text not null,
  wallet_address text not null,
  source_url text not null,
  asset_id text not null,
  side text not null check (side in ('bid', 'ask')),
  limit_price numeric(36, 12) not null,
  size numeric(36, 12) not null,
  notional_usd numeric(36, 6) not null,
  oid text not null,
  placed_at timestamptz,
  unique (snapshot_id, wallet_address, asset_id, side, oid)
);

create index if not exists idx_open_order_snapshots_success
  on public.open_order_snapshots (status, id desc);

create index if not exists idx_open_order_wallet_runs_snapshot
  on public.open_order_wallet_runs (snapshot_id, wallet_address);

create index if not exists idx_open_orders_snapshot_asset
  on public.open_orders (snapshot_id, asset_id, side, limit_price);

-- These snapshots contain tracked-wallet intelligence; only server-side service
-- role access is allowed. Vercel reads through the authenticated Express API.
alter table public.open_order_snapshots enable row level security;
alter table public.open_order_wallet_runs enable row level security;
alter table public.open_orders enable row level security;
