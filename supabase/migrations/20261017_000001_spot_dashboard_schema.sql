create table if not exists public.spot_snapshots (
  id bigint generated by default as identity primary key,
  status text not null check (status in ('running', 'success', 'partial', 'failed')),
  traders_scanned integer not null default 0,
  traders_with_filtered_holdings integer not null default 0,
  failures integer not null default 0,
  min_usd numeric(20, 2) not null,
  cache_ttl_hours numeric(10, 2) not null default 6,
  token_filter jsonb not null default '{}'::jsonb,
  generated_at timestamptz not null,
  error_message text,
  created_at timestamptz not null default timezone('utc', now()),
  finished_at timestamptz
);

create table if not exists public.spot_trader_runs (
  id bigint generated by default as identity primary key,
  snapshot_id bigint not null references public.spot_snapshots(id) on delete cascade,
  trader_name text not null,
  wallet_address text not null,
  source_url text not null,
  status text not null check (status in ('success', 'failed')),
  holdings_found integer not null default 0,
  total_value_usd numeric(20, 2) not null default 0,
  error_message text
);

create table if not exists public.spot_holdings (
  id bigint generated by default as identity primary key,
  snapshot_id bigint not null references public.spot_snapshots(id) on delete cascade,
  trader_name text not null,
  wallet_address text not null,
  source_url text not null,
  token text not null,
  value_usd numeric(20, 2) not null,
  filter_category text not null default 'displayable',
  scraped_at timestamptz not null
);

create index if not exists idx_spot_snapshots_status_created
  on public.spot_snapshots (status, created_at desc, id desc);

create index if not exists idx_spot_trader_runs_snapshot
  on public.spot_trader_runs (snapshot_id, id asc);

create index if not exists idx_spot_holdings_snapshot_token
  on public.spot_holdings (snapshot_id, token, value_usd desc);

-- The app accesses these tables only through the server-side service role.
-- Keep unauthenticated PostgREST clients from reading or modifying snapshots.
alter table public.spot_snapshots enable row level security;
alter table public.spot_trader_runs enable row level security;
alter table public.spot_holdings enable row level security;
